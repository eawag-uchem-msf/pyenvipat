def test_check_chemform_rejects_spaces_hard_error():
    with pytest.raises(ValueError, match="empty spaces"):
        check_chemform(data.isotopes, ["C1 H4"])


def test_check_chemform_accepts_single_string():
    got = check_chemform(data.isotopes, "C1H4")
    assert list(got["warning"]) == [False]
    assert list(got["new_formula"]) == ["C1H4"]


def test_check_chemform_nested_brackets():
    got = check_chemform(data.isotopes, ["(NH4)2SO4", "((CH2)2O)3", "(((C)))2"])
    assert list(got["warning"]) == [False, False, False]
    assert list(got["new_formula"]) == ["N2H8S1O4", "C6H12O3", "C2"]


def test_check_chemform_implicit_one_between_adjacent_elements():
    # No explicit counts anywhere -- every element gets an implicit "1",
    # including between two elements with no digit separating them.
    got = check_chemform(data.isotopes, ["NaCl", "NaK"])
    assert list(got["new_formula"]) == ["Na1Cl1", "Na1K1"]


def test_check_chemform_zero_count_is_valid():
    # Matches R: check_chemform(isotopes, "H0") -> warning FALSE, mass 0.
    got = check_chemform(data.isotopes, ["H0", "(H2O)0"])
    assert list(got["warning"]) == [False, False]
    assert list(got["monoisotopic_mass"]) == [0.0, 0.0]


def test_check_chemform_d_not_substituted_at_top_level():
    # D is its own element in `isotopes` (abundance 1); check_chemform does
    # NOT rewrite it to [2]H at the top level (unlike check_ded/mergeform/
    # subform/multiform), so D and [2]H formulas normalize to visibly
    # different strings and (very slightly) different masses -- the D and
    # [2]H rows of `isotopes` carry mass values differing in their last
    # digit. Reproduced exactly, not smoothed over.
    got = check_chemform(data.isotopes, ["D2O1", "[2]H2O1"])
    assert list(got["new_formula"]) == ["D2O1", "[2]H2O1"]
    assert got["monoisotopic_mass"].iloc[0] != got["monoisotopic_mass"].iloc[1]


def test_check_chemform_d_inside_bracket_group_is_substituted():
    # R quirk, reproduced verbatim: check_chemform's internal
    # bracket-multiplier helper *does* substitute D -> [2]H, so "(D2)3"
    # normalizes to "[2]H6", not "D6" (verified directly against R).
    got = check_chemform(data.isotopes, ["(D2)3"])
    assert got["new_formula"].iloc[0] == "[2]H6"


@pytest.mark.parametrize(
    "formula",
    [
        "()2CO2", "(CH4", "CH4)", "Xx2", "cH4", "2C", "[13]5", "]C2", "[C2",
        "6DBr9889", "C8G500Zn9", "CH4)2",
    ],
)
def test_check_chemform_invalid_formulas(formula):
    got = check_chemform(data.isotopes, [formula])
    assert bool(got["warning"].iloc[0]) is True
    assert got["new_formula"].iloc[0] == formula  # echoed back unmodified
    assert got["monoisotopic_mass"].iloc[0] == -9999


