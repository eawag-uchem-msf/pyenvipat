"""Golden-fixture and edge-case regression tests for envipat.formula
(issue #7): check_chemform, check_ded, mergeform, subform, multiform.

Golden-fixture tests compare against tests/golden/check_chemform/*.csv and
tests/golden/formula_algebra/*.csv, frozen from the real R package (v2.8)
in issue #3. String output is required to match
R exactly; monoisotopic mass is required to match exactly (see the
float_precision="round_trip" fix in envipat/data.py -- pandas' default CSV
float parser silently drops precision on ~1/4 of the isotopes table's
values, which broke exact-mass matching until fixed there).

A handful of cases here are *not* run against the golden fixtures as
literal ground truth, because the fixtures themselves (or the R functions
being ported) were found to be internally inconsistent -- see the
"Known R quirks" tests below and the MR description for the full writeup:

- R's check_ded/mergeform/subform/multiform tokenizers require every
  element to be followed by an explicit count; R's own adducts dataset
  ships two Formula_add values missing one ("F", "H2CO3"), and R either
  loops forever or silently mis-tokenizes on them. This port raises
  promptly instead. Note: the exported src/envipat/data/adducts.csv this
  port actually reads has been patched to "F1"/"H2C1O3" (see MR !7), so
  R and Python diverge on these two adducts rows. The tests
  below exercise the malformed strings directly (not via the CSV) to keep
  the general "reject missing explicit count" behaviour under regression.
- R's own adducts "M+H+NH4" entry (Formula_add "H1N1H4") has a
  duplicated, un-merged "H" token; R's mergeform doesn't deduplicate a
  formula's own tokens before merging, which trips a vector-recycling bug
  that silently corrupts *all* elements processed after the duplicate.
  An earlier version of this port merged such duplicates before
  combining, giving a chemically correct result instead of reproducing
  the corruption -- but per reviewer feedback on MR !7, quietly "fixing"
  malformed input like this is itself a footgun, so mergeform now raises
  ValueError promptly instead, same as the missing-count case above. As
  above, the exported adducts.csv has since been patched to "H5N1"; the
  test below exercises the original malformed string directly to keep
  this defensive behaviour under regression.
- formula_algebra/case_005.csv (multiform) was originally generated by a
  single vectorized R call `multiform(formula, c(1,2,3,0.5))` whose
  `fact` vector happened to exactly match the formula's 4-element count
  vector and got recycled element-wise against it, instead of four
  independent scalar calls -- all four rows held the *same* (wrong, for
  3 of the 4 factors) result. This has since been fixed by regenerating
  the fixture with four independent scalar calls (verified directly
  against R); it is now exercised as an ordinary golden fixture below,
  no longer as a documented divergence.
- Issue #14 resolved R's five-way-inconsistent handling of the `D`
  (deuterium) shorthand by canonicalizing `D` -> `[2]H` everywhere in
  this port (check_chemform's top level now substitutes like its
  in-group helper already did; check_ded's `formulas` argument now
  substitutes to `[2]H` like `deduct` already did). This is a genuine,
  permanent behavioural divergence from R (left unchanged, out of scope
  for #14), not a bug fix -- see the "D is substituted..." paragraph in
  envipat/formula.py's own module docstring for the full R-vs-Python
  writeup. check_chemform/case_002.csv rows 8/9 ("D2H2O1",
  "[13]C2C8D2H8[15]N2N2[18]O2O3") and formula_algebra/case_006.csv row 4
  ("C4D10"/"C4H10") are R's frozen reference output for these formulas
  and are deliberately *not* reproduced for those rows any more; the
  divergent Python results are asserted directly in
  test_check_chemform_d_canonicalized_to_deuterium and
  test_check_ded_d_canonicalized_to_deuterium below instead.

Run inside the dev container, after `pip install -e .`:
    pytest tests/python
"""

from pathlib import Path

