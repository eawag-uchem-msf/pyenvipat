def test_multiform_case_005_generator_bug_documented():
    # formula_algebra/case_005.csv was produced by ONE vectorized R call
    # `multiform("C10[13]C2H10Cl10", c(1,2,3,0.5))`, whose length-4 `fact`
    # vector happened to exactly match the formula's 4-element count
    # vector and got recycled element-wise against it -- NOT four
    # independent scalar calls. All 4 golden rows hold that single
    # (mostly-wrong) result. Correct, independently-verified-against-R
    # scalar semantics (multiform(formula, fact) for each fact alone):
    df = _read_golden(GOLDEN_ALGEBRA / "case_005.csv")
    assert set(df["result"]) == {"C10[13]C4H30Cl5"}  # the recycling artifact

    expected_scalar = {
        1.0: "C10[13]C2H10Cl10",
        2.0: "C20[13]C4H20Cl20",
        3.0: "C30[13]C6H30Cl30",
        0.5: "C5[13]C1H5Cl5",
    }
    for _, row in df.iterrows():
        got = multiform(row["formula_in"], row["fact"])[0]
        assert got == expected_scalar[row["fact"]]


