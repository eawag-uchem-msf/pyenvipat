def test_check_ded_d_canonicalized_to_deuterium():
    # R's check_ded substitutes D -> [2]H in `deduct` but D -> plain H in
    # each of `formulas`, so
    # check_ded(["C4D10"], "C4H10") is False in R (deduct's H10 read
    # against the formula's own D-as-H10: contained). Issue #14
    # canonicalized `formulas` to also substitute D -> [2]H, so both
    # sides now treat D as deuterium consistently: neither direction is
    # "contained" any more, since plain H and [2]H are different symbols.
    # formula_algebra/case_006.csv row 4 records R's (now superseded for
    # this row) "C4D10"/"C4H10" -> FALSE; see the test above.
    assert check_ded(["C4D10"], "C4H10") == [True]  # diverges from R (R: False)
    assert check_ded(["C4H10"], "C4D10") == [True]  # matches R (deduct side unaffected)


def test_d_substitution_does_not_clobber_longer_symbols():
    # check_ded/mergeform/subform's D -> [2]H (or -> H) substitution used
    # to be a bare substring replace (matching R's own unguarded
    # gsub("D", ...)), which corrupted any formula containing a real
    # element symbol starting with "D", e.g. dysprosium ("Dy", present in
    # isotopes): mergeform("C1H4", "Dy1") used to return "C1H4[2]Hy1".
    # Only R's multiform guarded against this (D(?![a-z])). This port now
    # applies that same guard everywhere a D substitution happens -- a
    # bug fix, not a behavioural port decision. (Issue #14 covers the
    # separate, bigger question of whether D -> [2]H/H/nothing should
    # also be made consistent across functions -- resolved by
    # canonicalizing to [2]H everywhere, see
    # test_check_chemform_d_canonicalized_to_deuterium /
    # test_check_ded_d_canonicalized_to_deuterium above.)
    assert mergeform("C1H4", "Dy1") == ["C1H4Dy1"]
    assert mergeform("Dy1", "C1H4") == ["Dy1C1H4"]
    assert subform("C1H4Dy1", "Dy1") == ["C1H4"]
    assert check_ded(["C1H4Dy1"], "Dy1") == [False]  # Dy1 is contained
    assert multiform("Dy2", 2) == ["Dy4"]


@pytest.mark.parametrize("malformed", ["F", "H2CO3"])
def test_flat_helpers_reject_missing_explicit_count(malformed):
    # R's mergeform/subform/check_ded/multiform tokenizer requires every
    # element to be followed by an explicit digit count; these two values
    # are the malformed Formula_add entries R's own adducts dataset ships
    # (see MR !7) -- R either loops
    # forever ("F": Formula_add of the M+F adduct) or silently
    # mis-tokenizes ("H2CO3": Formula_add of M+H2CO3-H, "C" and "O" glue
    # into one bogus "CO" pseudo-element). This port raises promptly, and
    # the exported adducts.csv Python reads has been patched to "F1"/
    # "H2C1O3" so these ValueErrors no longer fire off real adducts data;
    # kept here as general defensive-parsing regression coverage.
    with pytest.raises(ValueError):
        mergeform("C1H4", malformed)


def test_mergeform_rejects_repeated_element_in_one_formula():
    # R's own adducts "M+H+NH4" entry has Formula_add "H1N1H4"
    # (H appears twice, unmerged; see MR !7).
    # R's mergeform doesn't merge a formula's own repeated tokens before
    # combining, which trips a vector-recycling bug: it1 + it2 becomes a
    # length>1 vector for the repeated element, desynchronizing every
    # element processed afterwards. Verified directly against R:
    # mergeform("C1H4", "H1N1H4") returns "C1H5N8" in R -- chemically
    # nonsensical (8 nitrogens from a single N1 token). This port fails
    # loud instead of silently merging the duplicate to "fix" it -- same
    # treatment as the missing-count case above. The exported
    # adducts.csv Python reads has been patched to "H5N1" so this no
    # longer fires off real adducts data; kept here as general
    # defensive-parsing regression coverage.
    with pytest.raises(ValueError):
        mergeform("C1H4", "H1N1H4")

    with pytest.raises(ValueError):
        mergeform("H1N1H4", "C1H4")
