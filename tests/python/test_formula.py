"""Golden-fixture and edge-case regression tests for envipat.formula
(issue #7): check_chemform, check_ded, mergeform, subform, multiform.

Golden-fixture tests compare against tests/golden/check_chemform/*.csv and
tests/golden/formula_algebra/*.csv, frozen from the real R package (v2.8)
in issue #3 (see tools/make_golden.R). String output is required to match
R exactly; monoisotopic mass is required to match exactly (see the
float_precision="round_trip" fix in envipat/data.py -- pandas' default CSV
float parser silently drops precision on ~1/4 of the isotopes table's
values, which broke exact-mass matching until fixed there).

A handful of cases here are *not* run against the golden fixtures as
literal ground truth, because the fixtures themselves (or the R functions
being ported) were found to be internally inconsistent -- see the
"Known R quirks" tests below and the MR description for the full writeup:

- formula_algebra/case_005.csv (multiform) was generated by a single
  vectorized call `multiform(formula, c(1,2,3,0.5))` whose `fact` vector
  happened to exactly match `number1`'s length and got recycled
  element-wise against it, instead of four independent scalar calls -- all
  four rows hold the *same* (wrong, for 3 of the 4 factors) result.
  Verified directly against R with correct scalar calls instead.
- R's check_ded/mergeform/subform/multiform tokenizers require every
  element to be followed by an explicit count; R's own data/adducts.rda
  ships two Formula_add values missing one ("F", "H2CO3"), and R either
  loops forever or silently mis-tokenizes on them. This port raises
  promptly instead. Note: the exported src/envipat/data/adducts.csv this
  port actually reads has since been patched to "F1"/"H2C1O3" by
  tools/export_data.R (see MR !7) -- the source .rda is deliberately left
  broken, so R and Python diverge on these two adducts rows. The tests
  below exercise the malformed strings directly (not via the CSV) to keep
  the general "reject missing explicit count" behaviour under regression.
- R's own data/adducts.rda "M+H+NH4" entry (Formula_add "H1N1H4") has a
  duplicated, un-merged "H" token; R's mergeform doesn't deduplicate a
  formula's own tokens before merging, which trips a vector-recycling bug
  that silently corrupts *all* elements processed after the duplicate.
  An earlier version of this port merged such duplicates before
  combining, giving a chemically correct result instead of reproducing
  the corruption -- but per reviewer feedback on MR !7, quietly "fixing"
  malformed input like this is itself a footgun, so mergeform now raises
  ValueError promptly instead, same as the missing-count case above. As
  above, the exported adducts.csv has since been patched to "H5N1"; the
  test below exercises the original malformed string directly to keep
  this defensive behaviour under regression.

Run inside the dev container, after `pip install -e .`:
    pytest tests/python
"""

from pathlib import Path

import pandas as pd
import pytest

import envipat.data as data
from envipat.formula import check_chemform, check_ded, mergeform, multiform, subform

GOLDEN_CHEMFORM = Path(__file__).resolve().parents[2] / "tests" / "golden" / "check_chemform"
GOLDEN_ALGEBRA = Path(__file__).resolve().parents[2] / "tests" / "golden" / "formula_algebra"


def _read_golden(path):
    # keep_default_na=False: case_002's "" (invalid formula, edge case) is a
    # real empty *string* here, not a missing value.
    return pd.read_csv(path, float_precision="round_trip", keep_default_na=False)


# ---------------------------------------------------------------------------
# check_chemform: golden fixtures
# ---------------------------------------------------------------------------


def test_check_chemform_case_001_broad_pass_all_chemforms():
    exp = _read_golden(GOLDEN_CHEMFORM / "case_001.csv")
    got = check_chemform(data.isotopes, list(data.chemforms))
    assert len(got) == len(exp)
    pd.testing.assert_series_equal(got["warning"], exp["warning"], check_names=False)
    pd.testing.assert_series_equal(
        got["new_formula"], exp["new_formula"], check_names=False
    )
    # exact (bit-for-bit) float match, not just close
    mismatches = (got["monoisotopic_mass"].to_numpy() != exp["monoisotopic_mass"].to_numpy())
    assert not mismatches.any(), (
        f"{mismatches.sum()} mass mismatches, e.g. at "
        f"{list(data.chemforms)[mismatches.argmax()]!r}"
    )


def test_check_chemform_case_002_edge_cases():
    forms = [
        "C900Cl4H49", "O82394", "C8G500Zn9", "Br1", "6DBr9889", "",
        "C1H6O6", "D2H2O1", "[13]C2C8D2H8[15]N2N2[18]O2O3",
    ]
    exp = _read_golden(GOLDEN_CHEMFORM / "case_002.csv")
    got = check_chemform(data.isotopes, forms)
    for i, f in enumerate(forms):
        assert bool(got["warning"].iloc[i]) == bool(exp["warning"].iloc[i]), f
        assert got["new_formula"].iloc[i] == exp["new_formula"].iloc[i], f
        assert got["monoisotopic_mass"].iloc[i] == exp["monoisotopic_mass"].iloc[i], f


def test_check_chemform_case_003_get_sorted():
    # R input formulas for this case aren't stored in the golden fixture
    # (only get_sorted output); C2H4O1 / C1H2O1 / C1H3N1O2 reproduce it
    # exactly (verified against R directly -- see MR description).
    forms = ["C2H4O1", "C1H2O1", "C1H3N1O2"]
    exp = _read_golden(GOLDEN_CHEMFORM / "case_003.csv")
    got = check_chemform(data.isotopes, forms, get_sorted=True)
    for i in range(3):
        assert got["new_formula"].iloc[i] == exp["new_formula"].iloc[i]
        assert got["monoisotopic_mass"].iloc[i] == exp["monoisotopic_mass"].iloc[i]


def test_check_chemform_case_004_get_list():
    exp = _read_golden(GOLDEN_CHEMFORM / "case_004.csv")
    forms = list(dict.fromkeys(exp["formula"]))
    got = check_chemform(data.isotopes, forms, get_list=True)
    assert isinstance(got, list)
    assert len(got) == len(forms)
    for i, f in enumerate(forms):
        expected = dict(
            zip(
                exp.loc[exp["formula"] == f, "element"],
                exp.loc[exp["formula"] == f, "count"],
            )
        )
        assert got[i] == expected, f


